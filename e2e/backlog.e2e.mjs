test('TC-BKL-21: New Feature with a Start Date and a Target date asks for the hours of every month from the start to the target', async () => {
  const { page, context, errors } = await openPage(app, { roles: true })
  await scheduleServed(context)
  await loadSample(page)
  await navigate(page, 'QMS-0025')
  await page.getByRole('button', { name: '＋ New Feature' }).first().click()
  const form = page.locator('form.nf-form')
  await form.waitFor()
  // Months in UTC, as the app uses for Time Writing (NAV-11, NAV-51).
  const utcMonth = new Date().toISOString().slice(0, 7)
  const [year, month] = utcMonth.split('-').map(Number)
  const at = (offset) => { const date = new Date(Date.UTC(year, month - 1 + offset, 1)); return { iso: date.toISOString().slice(0, 10), label: date.toLocaleDateString('en-US', { month: 'long', year: 'numeric', timeZone: 'UTC' }) } }
  const next = at(1), third = at(3)
  assert.match(await text(form.locator('.nf-months')), new RegExp(`one Task for ${at(0).label} \\(Start date empty: from today\\)`), 'no dates: this month only')
  await form.getByLabel('Start date', { exact: true }).fill(next.iso)
  assert.match(await text(form.locator('.nf-months')), new RegExp(`one Task for ${next.label}`), 'a release starting next month: no Task for this month')
  await form.getByLabel('Target date', { exact: true }).fill(third.iso)
  assert.match(await text(form.locator('.nf-months')), new RegExp(`3 month Tasks, ${next.label} – ${third.label}`))
  await form.getByLabel('Target date', { exact: true }).fill(at(-1).iso)
  assert.match(await text(form.locator('.nf-months')), /The Target date is before the Start Date/)
  await form.getByLabel('Target date', { exact: true }).fill(third.iso)
  await fillFeatureStep(form)
  await form.getByLabel(/^Feature DoD/).fill('All deliverables reviewed.')
  await form.getByRole('button', { name: 'Continue' }).click()
  await form.locator('fieldset.milestone-choices').first().locator('input[type=checkbox]').first().check()
  await form.getByRole('button', { name: 'Continue' }).click()
  const estimates = form.getByRole('region', { name: `Section 4: Estimates for ${next.label} – ${third.label}` })
  assert.ok(await estimates.isVisible(), 'the estimates section names the months')
  const rows = await estimates.locator('tbody th').allTextContents()
  assert.deepEqual(rows.map((row) => row.replace(/ · ad-hoc$/, '').trim()), [next.label, at(2).label, third.label], 'one row per month')
  await estimates.getByLabel(`Original Estimate (h) ${next.label}`).fill('10')
  await estimates.getByLabel(`Original Estimate (h) ${third.label}`).fill('6')
  assert.equal(await estimates.getByLabel(`Completed Work (h) ${next.label}`).isDisabled(), true, 'no Completed Work for a future month')
  assert.equal((await text(estimates.locator('tfoot td').first())).trim(), '16')
  // TC-BKL-37 (BKL-48): the month Tasks tick box is in the Time Writing section too, ticked by default; unticking it
  // (here or in the Feature section: one choice) leaves one Task, ticking it again brings the months and their hours back.
  const section4 = form.getByRole('region', { name: /^Section 4: Estimates for / }) // its name follows the months
  const monthsBox = section4.getByRole('checkbox', { name: 'Create Time Writing month Tasks from the Start date to the Target date' })
  assert.equal(await monthsBox.isChecked(), true, 'ticked by default for a Feature')
  await monthsBox.uncheck()
  await section4.locator('.nf-estimates').waitFor()
  assert.equal(await section4.locator('.nf-month-hours').count(), 0, 'unticked: one Task, no month table')
  assert.equal(await form.locator('#nf-months-help').count(), 1, 'the Feature section shows the same tick box')
  assert.match(await text(form.locator('#nf-tw-months-help')), /Not ticked: one Time Writing Task/)
  await monthsBox.check()
  await section4.locator('.nf-month-hours').waitFor()
  assert.equal((await text(section4.locator('tfoot td').first())).trim(), '16', 'the hours typed per month are kept')
  assert.match(await text(form.getByRole('definition').last()), new RegExp(`3 months, ${next.label} – ${third.label}`))
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), false)
  await form.getByRole('button', { name: 'Cancel' }).click()
  assert.deepEqual(errors.filter((entry) => !/401|Unauthorized/.test(entry)), [])
  await context.close()
})

