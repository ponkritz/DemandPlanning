// BKL-29: step 1 needs a PI → Sprint; the schedule is served here (a current PI and Sprint around today), every
// other Azure DevOps call is refused, so nothing is written.
async function scheduleServed(context) {
  const day = (offset) => new Date(Date.now() + offset * 86400000).toISOString().slice(0, 10) + 'T00:00:00Z'
  const dates = { startDate: day(-20), finishDate: day(40) }, sprint = { startDate: day(-5), finishDate: day(9) }
  await context.route(/dev\.azure\.com/, (route) => /teamsettings\/iterations/.test(route.request().url())
    ? route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ value: [{ name: 'PI 99', path: 'E2E\\PI 99', attributes: dates }, { name: 'Sprint 99.1', path: 'E2E\\PI 99\\Sprint 99.1', attributes: sprint }] }) })
    : route.fulfill({ status: 401, contentType: 'application/json', body: '{"message":"Unauthorized"}' }))
}
async function fillFeatureStep(form) {
  const epic = form.getByLabel('Parent Epic')
  await epic.selectOption({ index: 1 })
  await form.getByLabel('Feature title').fill('E2E Program | Service | Release 1')
  await form.getByLabel(/^PAT/).fill('e2e-token')
  await form.getByRole('button', { name: '↻ Reload' }).click()
  const schedule = form.getByLabel('PI / Sprint schedule')
  const option = schedule.locator('option', { hasText: 'Sprint 99.1' })
  await option.waitFor({ state: 'attached' })
  await schedule.selectOption(await option.getAttribute('value'))
}

test('TC-BKL-15: New Feature offers your own User Story (title and description) under the new Feature', async () => {
  const { page, context, errors } = await openPage(app)
  await scheduleServed(context)
  await loadSample(page)
  await navigate(page, 'QMS-0025')
  await page.getByRole('button', { name: '＋ New Feature' }).first().click()
  const form = page.locator('form.nf-form')
  await form.waitFor()
  await fillFeatureStep(form)
  await form.getByLabel(/^Feature DoD/).click()
  await form.getByRole('heading', { name: /Feature$/ }).click()
  const own = form.locator('fieldset.nf-own-story')
  assert.match(await text(own.locator('legend')), /Your own User Story/)
  await own.getByRole('textbox', { name: /^User Story title/ }).fill('Write the plan')
  await own.getByRole('textbox', { name: /^User Story description/ }).fill('Why and what')
  assert.equal(await own.getByRole('textbox', { name: /^Comment/ }).count(), 1, 'BKL-27: an optional first comment here too')
  await form.getByRole('button', { name: 'Cancel' }).click()
  assert.deepEqual(errors.filter((entry) => !/401|Unauthorized/.test(entry)), [])
  await context.close()
})

test('TC-BKL-19: New Feature shows its sections one after another: Feature, then the DoD, then the User Stories, then the month estimates', async () => {
  const { page, context, errors } = await openPage(app)
  await scheduleServed(context)
  await loadSample(page)
  await navigate(page, 'QMS-0025')
  await page.getByRole('button', { name: '＋ New Feature' }).first().click()
  const form = page.locator('form.nf-form')
  await form.waitFor()
  const section = (name) => form.getByRole('region', { name })
  const visible = async () => (await form.locator('section.nf-step:visible h3').allInnerTexts()).map((entry) => entry.replace(/\s+/g, ' ').trim().replace(/ —.*/, ''))
  const outside = () => form.getByRole('heading', { name: /Feature$/ }).click()
  assert.deepEqual(await visible(), ['1 Feature'], 'only section 1 at first')
  assert.match(await section('Section 1: Feature').getAttribute('class'), /nf-current/, 'the section to fill is highlighted')
  assert.match(await text(form.getByRole('note')), /To go on, fill in the Parent Epic, the title, the PI → Sprint/)
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), true)
  await fillFeatureStep(form)
  assert.deepEqual(await visible(), ['✓ Feature', '2 Definition of Done'], 'section 1 filled: only the DoD appears next')
  assert.match(await section('Section 2: Definition of Done').getAttribute('class'), /nf-current/)
  assert.match(await text(form.getByRole('note')), /Check the DoD, then click outside this section to go on/)
  const dod = form.getByLabel(/^Feature DoD/)
  await dod.fill('')
  await outside()
  assert.deepEqual(await visible(), ['✓ Feature', '2 Definition of Done'], 'an empty DoD keeps the next sections hidden')
  assert.match(await text(form.getByRole('note')), /fill in the DoD/)
  await dod.fill('IQOQ finished and Checklist uploaded into the Feature.')
  await outside()
  assert.deepEqual(await visible(), ['✓ Feature', '✓ Definition of Done', '3 User Stories'], 'leaving the filled DoD shows the User Stories')
  assert.match(await text(form.getByRole('note')), /Choose the User Stories, then click outside this section to go on/)
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), true, 'not every section is done')
  await form.locator('fieldset.milestone-choices').first().locator('input[type=checkbox]').first().check()
  await outside()
  const shown = await visible()
  assert.deepEqual(shown.slice(0, 3), ['✓ Feature', '✓ Definition of Done', '✓ User Stories'])
  assert.match(shown[3], /^4 Estimates for \w+ \d{4}$/, 'leaving the User Stories shows the estimates')
  assert.ok(await form.getByLabel('Original Estimate (h)').isVisible())
  assert.ok(await form.getByLabel('Completed Work (h)').isVisible())
  assert.match(await text(form.getByRole('definition').first()), /E2E Program \| Service \| Release 1/)
  assert.equal(await form.getByRole('button', { name: 'Next' }).count(), 0, 'no Next button: one page')
  await form.getByLabel('Feature title').press('Enter')
  assert.equal(await form.getByRole('alert').count(), 0, 'Enter in the title does not create the Feature')
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), false, 'every section shown: Save is on')
  await form.getByRole('button', { name: 'Cancel' }).click()
  assert.deepEqual(errors.filter((entry) => !/401|Unauthorized/.test(entry)), [])
  await context.close()
})
