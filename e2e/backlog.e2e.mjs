test('TC-BKL-19: New Feature shows its sections one after another: Feature, then the DoD, then the User Stories, then the month estimates', async () => {
  const { page, context, errors } = await openPage(app)
  await scheduleServed(context)
  await loadSample(page)
  await navigate(page, 'QMS-0025')
  await page.getByRole('button', { name: '＋ New Feature' }).first().click()
  const form = page.locator('form.nf-form')
  await form.waitFor()
  const section = (name) => form.getByRole('region', { name })
  const visible = async () => (await form.locator('section.nf-step:visible h3').allInnerTexts()).map((entry) => entry.replace(/\s+/g, ' ').trim().replace(/ —.*/, ''))
  const outside = () => form.getByRole('heading', { name: /Feature$/ }).click()
  const proceed = () => form.getByRole('button', { name: 'Continue' }).click()
  assert.deepEqual(await visible(), ['1 Feature'], 'only section 1 at first')
  assert.match(await section('Section 1: Feature').getAttribute('class'), /nf-current/, 'the section to fill is highlighted')
  assert.match(await text(form.getByRole('note')), /To go on, fill in the Parent Epic, the title, the PI → Sprint/)
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), true)
  await fillFeatureStep(form)
  assert.deepEqual(await visible(), ['✓ Feature', '2 Definition of Done'], 'section 1 filled: only the DoD appears next')
  assert.match(await section('Section 2: Definition of Done').getAttribute('class'), /nf-current/)
  assert.match(await text(form.getByRole('note')), /Check the DoD, then Continue/)
  const dod = form.getByLabel(/^Feature DoD/)
  await dod.fill('IQOQ finished.')
  await outside()
  assert.deepEqual(await visible(), ['✓ Feature', '2 Definition of Done'], 'BKL-30: clicking outside no longer moves on')
  await dod.fill('')
  assert.deepEqual(await visible(), ['✓ Feature', '2 Definition of Done'], 'an empty DoD keeps the next sections hidden')
  assert.match(await text(form.getByRole('note')), /fill in the DoD/)
  assert.equal(await form.getByRole('button', { name: 'Continue' }).count(), 0, 'no Continue while something is missing')
  await dod.fill('IQOQ finished and Checklist uploaded into the Feature.')
  await proceed()
  assert.deepEqual(await visible(), ['✓ Feature', '✓ Definition of Done', '3 User Stories'], 'Continue shows the User Stories')
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('aria-label')), 'Section 3: User Stories', 'the focus moves to the new section')
  assert.match(await text(form.getByRole('note')), /Choose the User Stories, then Continue/)
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), true, 'not every section is done')
  await form.locator('fieldset.milestone-choices').first().locator('input[type=checkbox]').first().check()
  await proceed()
  const shown = await visible()
  assert.deepEqual(shown.slice(0, 3), ['✓ Feature', '✓ Definition of Done', '✓ User Stories'])
  assert.match(shown[3], /^4 Estimates for \w+ \d{4}$/, 'Continue shows the estimates')
  assert.ok(await form.getByLabel('Original Estimate (h)').isVisible())
  assert.ok(await form.getByLabel('Completed Work (h)').isVisible())
  assert.match(await text(form.getByRole('definition').first()), /E2E Program \| Service \| Release 1/)
  assert.equal(await form.getByRole('button', { name: 'Next' }).count(), 0, 'no Next button: one page')
  await form.getByLabel('Feature title').press('Enter')
  assert.equal(await form.getByRole('alert').count(), 0, 'Enter in the title does not create the Feature')
  assert.equal(await form.getByRole('button', { name: 'Save' }).isDisabled(), false, 'every section shown: Save is on')
  await form.getByRole('button', { name: 'Cancel' }).click()
  assert.deepEqual(errors.filter((entry) => !/401|Unauthorized/.test(entry)), [])
  await context.close()
})

test('TC-EPS-01: Epic setup — its fields appear in New Feature (a value list, required and warning fields), the title follows its pattern, and Admin → Epic setup shows them', async () => {
  const { page, context, errors } = await openPage(app)
  await loadSample(page)
  await navigate(page, 'QMS-0025')
  await page.getByRole('button', { name: '＋ New Feature' }).first().click()
  let form = page.locator('form.nf-form')
  await form.waitFor()
  const epicValue = await form.getByLabel('Parent Epic').locator('option').nth(2).getAttribute('value'), epicId = Number(epicValue.split('/').pop())
  await form.getByRole('button', { name: 'Cancel' }).click()
  // The shared Epic setup as last read from Git (kept in this browser): Platform from a list into the Title, Program
  // required into the Description, Owner warns when empty.
  await page.evaluate((id) => localStorage.setItem('demand-planning-epic-setup-v1', JSON.stringify({ schema: 1, kind: 'epic-setup', lists: [{ id: 'platform', name: 'Platform', values: ['Platform 1.0', 'Platform 2.0'] }], epics: [{ epicId: id, epicTitle: 'E2E Epic', titlePattern: '{platform} | {feature}', fields: [
    { label: 'Platform', type: 'list', list: 'platform', ifEmpty: 'block', into: 'title' },
    { label: 'Program', type: 'text', ifEmpty: 'block', into: 'description' },
    { label: 'Owner', type: 'text', ifEmpty: 'warn', into: 'description' },
  ] }] })), epicId)
  await page.reload()
  await page.locator('.sidebar nav').waitFor()
  await navigate(page, 'QMS-0025')
  await page.getByRole('button', { name: '＋ New Feature' }).first().click()
  form = page.locator('form.nf-form')
  await form.waitFor()
  await form.getByLabel('Parent Epic').selectOption(epicValue)
  const platform = form.locator('.nf-fields select')
  assert.deepEqual((await platform.locator('option').allInnerTexts()).map((entry) => entry.trim()), ['Required…', 'Platform 1.0', 'Platform 2.0'], 'the list values')
  assert.match(await text(form.locator('.nf-fields')), /Platform \*.*Program \*.*Owner/s, 'required fields are marked')
  assert.match(await text(form), /Empty: Owner — the Feature is created/, 'a Warn field says so')
  await platform.selectOption('Platform 2.0')
  assert.equal(await form.getByLabel('Feature title').inputValue(), 'Platform 2.0', 'the title follows the pattern (an empty {feature} is dropped)')
  await form.getByRole('button', { name: 'Cancel' }).click()
  // Admin → Epic setup: the fields and the list, read-only without Git storage.
  await navigate(page, 'Epic & Feature setup')
  assert.equal(await text(page.locator('header.topbar h1')), 'Epic & Feature setup')
  // CON-97: Setup per Epic — the Epic in the list, its fields read-only without Git storage, the preview.
  await page.getByRole('tablist', { name: 'Sections' }).getByRole('tab', { name: 'Setup per Epic' }).click()
  const listed = page.locator('.efe-epics button', { hasText: `#${epicId}` })
  assert.match(await text(listed), /1 of 4 customized/, 'the Epic shows what it customizes')
  await listed.click()
  assert.equal(await page.getByRole('switch', { name: 'Customize Fields and title for this Epic' }).getAttribute('aria-checked'), 'true')
  assert.equal(await page.getByLabel('Field 1 label').inputValue(), 'Platform')
  assert.equal(await page.getByLabel('Field 1 label').isDisabled(), true, 'read-only without Git storage')
  assert.match(await text(page.locator('.efe-preview')), /Title Platform 1\.0 \| Feature title.*Description .*Program : Program.*Owner : Owner/s)
  await page.getByRole('tablist', { name: 'Sections' }).getByRole('tab', { name: 'Value lists' }).click()
  assert.equal(await page.getByLabel('Values of Platform').inputValue(), 'Platform 1.0\nPlatform 2.0')
  assert.deepEqual(errors, [])
  await context.close()
})
