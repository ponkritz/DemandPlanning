test('TC-CAP-13: Pulse Check shows Utilization = utilized ÷ (contractual − absence) with Trainings and Other NPRA apart', async () => {
  const { page, context, errors } = await openPage(app)
  await loadSample(page)
  await navigate(page, 'Pulse Check')
  await page.getByRole('tablist', { name: 'Pulse Check sections' }).getByRole('tab', { name: /^Last month/ }).click()
  const table = page.locator('.panel', { has: page.locator('h2, h3', { hasText: /^Who has capacity/ }) }).first().locator('table')
  await table.waitFor()
  assert.deepEqual((await table.locator('thead th').allInnerTexts()).map((label) => label.trim().toLowerCase()), ['person', 'status', 'funded hours', 'absence', 'available hours', 'project work', 'training', 'other npra', 'common activities', 'total planned', 'total actual', 'actual utilization', 'main stream'])
  // Every row: Available hours = Contractual − Absence hours (at least 0) and Total actual = Project work + Training + Other NPRA + Common activities.
  const number = (value) => Number(value.replace(/[^\d.]/g, '') || 0)
  for (const row of await table.locator('tbody tr').all()) {
    const cells = (await row.locator('td').allInnerTexts()).map((cell) => cell.trim())
    const [contractual, absence, available, work, trainings, other, activities, , utilized] = cells.slice(2, 11).map(number)
    assert.ok(Math.abs(available - Math.max(0, contractual - absence)) < 0.02, `available = contractual − absence (${cells[0]})`)
    assert.ok(Math.abs(utilized - (work + trainings + other + activities)) < 0.05, `total actual = project work + training + other NPRA + common activities (${cells[0]})`)
  }
  // CAP-52: four clean cards, each with its formula in brackets, in the default profile's names.
  const cards = (await page.locator('.metric-grid article').allInnerTexts()).map((card) => card.replace(/\s+/g, ' ').trim())
  assert.equal(cards.length, 4, 'Utilization, Funded Hours, Absence, NPRA Hours')
  assert.match(cards[0], /utilization .*\[Total actual ÷ Available hours\]$/)
  assert.match(cards[1], /^Funded Hours [\d.,]+h \[Working days × Funded hrs per day \(8h\)\]$/)
  assert.match(cards[2], /^Absence [\d.,]+h \[Holiday \+ PTO \+ Sick \+ Unplanned \+ Other\]$/)
  assert.match(cards[3], /^NPRA Hours [\d.,]+h \[Tagged NPRA hours, training included\]$/)
  assert.match(await text(page.locator('.panel', { has: page.locator('h2, h3', { hasText: /^Who has capacity/ }) }).first()), /\d+ people · \d+ overloaded · \d+ with capacity/, 'Overloaded and Has capacity counted with the table')
  assert.deepEqual(errors, [])
  await context.close()
})

