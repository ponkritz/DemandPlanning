test('TC-SET-06: each Settings page is its own menu entry; its sections show one at a time and the last one is remembered', async () => {
  const { page, context, errors } = await openPage(app)
  await navigate(page, /Azure DevOps$/)
  assert.equal(await text(page.locator('header.topbar h1')), 'Azure DevOps', 'the header names the Settings page')
  const sections = page.getByRole('tablist', { name: 'Sections' })
  assert.deepEqual((await sections.getByRole('tab').allInnerTexts()).map((label) => label.trim()), ['Your work email', 'Servers and PATs', 'Stream mapping', 'Other views', 'Synthetic sample'])
  await sections.getByRole('tab', { name: 'Stream mapping' }).click()
  await page.locator('.panel', { has: page.locator('h2, h3', { hasText: /^Stream mapping/ }) }).first().waitFor()
  assert.equal(await page.locator('.panel', { has: page.locator('h2, h3', { hasText: /^Servers and PATs/ }) }).count(), 0, 'one section at a time')
  // KB-24: the connection editor opens from the Stream mapping section itself (it was only rendered with Other views).
  const mappingPanel = page.locator('.panel', { has: page.locator('h2, h3', { hasText: /^Stream mapping/ }) }).first()
  await mappingPanel.locator('tbody tr').first().getByRole('button', { name: /^(Set up|Add query|Edit)$/ }).first().click()
  const editor = page.getByRole('dialog')
  await editor.waitFor()
  assert.equal(await editor.locator('form.connection-editor').count(), 1, 'the connection editor opens on the Stream mapping page')
  await editor.getByRole('button', { name: 'Cancel' }).click()
  await editor.waitFor({ state: 'detached' })
  // Another page and back: the section shown last is remembered.
  await navigate(page, 'Storage')
  assert.equal(await text(page.locator('header.topbar h1')), 'Storage')
  assert.deepEqual((await page.getByRole('tablist', { name: 'Sections' }).getByRole('tab').allInnerTexts()).map((label) => label.trim()), ['Git storage', 'Shared setup in Git', 'SharePoint'])
  await navigate(page, /Azure DevOps$/)
  assert.equal(await page.getByRole('tablist', { name: 'Sections' }).getByRole('tab', { name: 'Stream mapping' }).getAttribute('aria-selected'), 'true')
  // A page with one section has no section row.
  await navigate(page, 'Feature setup')
  assert.equal(await page.getByRole('tablist', { name: 'Sections' }).count(), 0)
  assert.deepEqual(errors, [])
  await context.close()
})

